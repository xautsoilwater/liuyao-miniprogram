function applyLearningBoosts(articles) {
  if (!Array.isArray(articles)) return articles
  return articles.map((article) => {
    const extra = BOOST[article.id]
    if (!extra || !extra.length) return article
    const blocks = (article.blocks || []).slice()
    // 替换更弱的 path 图为 vols8（若存在）
    for (let i = 0; i < blocks.length; i += 1) {
      const b = blocks[i]
      if (b && b.type === 'figure' && b.key === 'path' && article.id === 'xueyi-lujing') {
        blocks[i] = figure('vols8', b.caption || '学易八卷路径')
      }
      if (b && b.type === 'figure' && (b.key === 'bagua-table') && article.category === '象数') {
        // 保留 ring，另在 boost 里已加 grid
      }
    }
    const last = blocks[blocks.length - 1]
    if (last && last.type === 'note') {
      blocks.splice(blocks.length - 1, 0, ...extra)
    } else {
      blocks.push(...extra)
    }
    // 略加厚 summary 的阅读预期（不改标题）
    let summary = article.summary || ''
    if (summary && summary.indexOf('详解') < 0 && summary.length < 36) {
      summary = summary.replace(/。?$/, '') + ' · 含图示与练习要点。'
    }
    return Object.assign({}, article, { blocks, summary })
  })
}

