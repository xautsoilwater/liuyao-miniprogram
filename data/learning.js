function normalizeArticle(article) {
  if (!article) return null
  if (article.blocks && article.blocks.length) return article
  const blocks = (article.content || []).map((text) => p(text))
  return Object.assign({}, article, { blocks, cover: article.cover || 'taiji' })
}

function getArticle(id) {
  const raw = ARTICLES.find((item) => item.id === id) || null
  const article = normalizeArticle(raw)
  if (!article) return null
  const meta = CATEGORY_META[article.category] || {}
  return Object.assign({}, article, {
    categoryLabel: meta.vol ? `${meta.vol} · ${article.category}` : article.category
  })
}

function groupByCategory() {
  const map = {}
  ARTICLES.forEach((item) => {
    if (!map[item.category]) map[item.category] = []
    map[item.category].push(normalizeArticle(item))
  })
  const keys = CATEGORY_ORDER.filter((c) => map[c]).concat(
    Object.keys(map).filter((c) => !CATEGORY_ORDER.includes(c))
  )
  return keys.map((category) => {
    const meta = CATEGORY_META[category] || {}
    return {
      category,
      vol: meta.vol || '',
      subtitle: meta.subtitle || '',
      label: meta.vol ? `${meta.vol} · ${category}` : category,
      items: map[category]
    }
  })
}

