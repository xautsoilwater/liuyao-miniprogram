function getXiaoxiang(alias, lineIndex) {
  const arr = XIAOXIANG[alias]
  if (!arr || lineIndex < 0 || lineIndex > 5) return ''
  return arr[lineIndex] || ''
}

function glossXiaoxiang(xx) {
  const t = String(xx || '')
  if (!t) return ''
  // 取末尾「……也」类理由
  const parts = t.split(/[。；]/).filter(Boolean)
  for (let i = parts.length - 1; i >= 0; i -= 1) {
    const p = parts[i].trim()
    const m = p.match(/([^，、；]+)也$/)
    if (!m) continue
    const key = m[1].replace(/^(其|以|亦|又)/, '')
    // 精确与模糊
    if (REASON_GLOSS[m[1]]) return REASON_GLOSS[m[1]]
    if (REASON_GLOSS[key]) return REASON_GLOSS[key]
    for (const k of Object.keys(REASON_GLOSS)) {
      if (m[1].indexOf(k) >= 0 || k.indexOf(m[1]) >= 0) return REASON_GLOSS[k]
    }
  }
  // 整句命中
  for (const k of Object.keys(REASON_GLOSS)) {
    if (t.indexOf(k) >= 0) return REASON_GLOSS[k]
  }
  return ''
}

function matchSageExtra(classic, tip, xiaoxiang) {
  const blob = [classic, tip, xiaoxiang].join('｜')
  for (let i = 0; i < SAGE_EXTRA.length; i += 1) {
    if (SAGE_EXTRA[i].re.test(blob)) {
      const s = SAGE_EXTRA[i]
      return (s.from ? s.from + '：' : '') + '「' + s.quote + '」'
    }
  }
  return ''
}

/**
 * 生成圣言旁参行：小象 + 白话点睛 + 可选圣贤名句
 */
function buildYaoSageLine(alias, lineIndex, classic, tip) {
  const xx = getXiaoxiang(alias, lineIndex)
  const chunks = []
  if (xx) {
    const body = xx.replace(/^[「"]+/, '').replace(/[」"]+$/, '').replace(/[。．]+$/, '')
    let block = '《象》曰：「' + body + '」'
    const gloss = glossXiaoxiang(xx)
    if (gloss) block += '——' + gloss
    chunks.push(block)
  }
  const extra = matchSageExtra(classic, tip, xx)
  if (extra) chunks.push('旁参' + extra)
  return chunks.join('。').replace(/。{2,}/g, '。').replace(/^[。\s]+|[。\s]+$/g, (m, off, s) => {
    // 仅去掉首尾多余句号，保留中间
    return off === 0 ? '' : (m.indexOf('。') >= 0 ? '。' : '')
  }).replace(/。$/,'') // 末尾不强制句号，由展示决定
    .trim()
}

/**
 * 白话仅在空缺时用小象点睛补位；有白话则不与 sage 行重复
 */
function enrichYaoTip(tip, xiaoxiang) {
  const t = String(tip || '').trim()
  if (t) return t.replace(/。{2,}/g, '。')
  const gloss = glossXiaoxiang(xiaoxiang)
  return gloss ? gloss + '。' : ''
}

